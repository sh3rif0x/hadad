#!/usr/bin/env node
/**
 * add-service-icons.js  (v2)
 * Run from your project root:   node add-service-icons.js
 * Or pass the root folder:      node add-service-icons.js path/to/project
 *
 * - Loads the Lucide icon library (one small script, from a CDN)
 * - Puts a big colored icon above each service title (centered)
 * - Removes the numbers (1 2 3 4 ...) from the service cards
 * - Centers icon + title + text + button, with a cleaner card UI
 *
 * Safe to re-run. Backups are saved as <file>.bak (first run only).
 * To change an icon, edit the ICONS list below (names from https://lucide.dev/icons)
 */

