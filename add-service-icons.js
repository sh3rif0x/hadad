/*
 * Runtime script (runs in the browser, after the page loads):
 *  1. creates the Lucide icons
 *  2. finds each service card (the smallest container that holds one icon
 *     and the text "اطلب الخدمة") and marks it with .service-card-centered
 *  3. removes number-only elements (1, 2, 01, ٣ ...) inside the card
 *  4. neutralizes numbers generated by CSS (::before / ::after / counters)
 */
const RUNTIME_JS = `<script>
(function () {
    function init() {
        if (window.lucide) lucide.createIcons();

        var DIGITS = /^[\\s\\u00a0]*[0-9\\u0660-\\u0669\\u06f0-\\u06f9]{1,2}[\\s.\\-)\\/:]*$/;
        var PSEUDO_NUM = /counter|^["'][\\s]*[0-9\\u0660-\\u0669\\u06f0-\\u06f9]/;

        document.querySelectorAll(".service-icon").forEach(function (icon) {
            var card = icon.parentElement;
            while (card && card !== document.body) {
                if (
                    card.querySelectorAll(".service-icon").length === 1 &&
                    card.textContent.indexOf("اطلب الخدمة") > -1
                ) break;
                card = card.parentElement;
            }
            if (!card || card === document.body) card = icon.parentElement;

            card.classList.add("service-card-centered");

            // 1) remove number-only elements
            card.querySelectorAll("*").forEach(function (el) {
                if (el.closest(".service-icon")) return;
                if (el.children.length === 0 && DIGITS.test(el.textContent)) el.remove();
            });

            // 2) remove numbers created by CSS pseudo-elements
            [card].concat([].slice.call(card.querySelectorAll("*"))).forEach(function (el) {
                if (el.closest && el.closest(".service-icon")) return;
                ["::before", "::after"].forEach(function (p) {
                    var c = getComputedStyle(el, p).content;
                    if (c && c !== "none" && c !== "normal" && PSEUDO_NUM.test(c)) {
                        el.classList.add("sv-nopseudo");
                    }
                });
            });
        });
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", init);
    } else {
        init();
    }
})();
</script>`;

function fixHtml() {
    const file = findFile(["index.html", "1.html"]);
    if (!file) return console.error("✗ index.html not found (run from your project root)");
    backupOnce(file);
    let src = fs.readFileSync(file, "utf8");

    const missing = [];

    ICONS.forEach(({ title, icon }) => {
        // a heading with exactly this title, followed shortly by "اطلب الخدمة" (= it's a service card)
        const re = new RegExp("<(h[2-6])([^>]*)>\\s*" + escRe(title) + "\\s*</\\1>", "g");
        let found = false;
        let m;

        while ((m = re.exec(src)) !== null) {
            const after = src.slice(m.index, m.index + 900);
            if (after.indexOf("اطلب الخدمة") === -1) continue; // not the services card

            found = true;
            const before = src.slice(Math.max(0, m.index - 200), m.index);
            if (/class="service-icon"[^>]*>\s*<i data-lucide="[^"]*"><\/i><\/span>\s*$/.test(before)) break; // already has an icon

            const iconHtml =
                '<span class="service-icon" aria-hidden="true"><i data-lucide="' + icon + '"></i></span>\n';
            src = src.slice(0, m.index) + iconHtml + src.slice(m.index);
            break;
        }

        if (!found) missing.push(title);
    });

    // library + runtime script, before </body>
    const scriptBlock = '<script src="' + LUCIDE_URL + '"></script>\n' + RUNTIME_JS;

    src = upsert(src, "<!-- ICONS:START -->", "<!-- ICONS:END -->", scriptBlock, (c, block) => {
        const m = /<\/body>/i.exec(c);
        return m ? c.slice(0, m.index) + block + "\n" + c.slice(m.index) : c + "\n" + block;
    });

    fs.writeFileSync(file, src);
    console.log("✓ " + path.relative(ROOT, file) + " updated");

    if (missing.length) {
        console.warn("\n! Could not find these service titles as headings (h2-h6) next to 'اطلب الخدمة':");
        missing.forEach((t) => console.warn("   - " + t));
        console.warn("  Send me the HTML of one service card and I will match it exactly.");
    }
}

